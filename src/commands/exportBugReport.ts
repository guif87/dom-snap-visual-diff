import * as vscode from 'vscode';
import * as os from 'os';

export interface DefectPayloadOptions {
  url: string;
  mismatchPercentage?: number;
  diffPixels?: number;
  missingTestIds?: string[];
  consoleErrors?: string[];
}

export function generateBugReportMarkdown(options: DefectPayloadOptions): string {
  const testIdsSection =
    options.missingTestIds && options.missingTestIds.length > 0
      ? `### Missing / Dropped Test Attributes\n${options.missingTestIds.map((id) => `- \`data-testid="${id}"\``).join('\n')}\n`
      : '';

  const errorsSection =
    options.consoleErrors && options.consoleErrors.length > 0
      ? `### Console Errors Captured\n${options.consoleErrors.map((e) => `- \`${e}\``).join('\n')}\n`
      : '### Console Errors\n- No unhandled runtime errors captured.\n';

  return `## [Defect Report] UI Regression Detected on \`${options.url}\`

### Summary & Impact
- **Visual Discrepancy:** ${options.mismatchPercentage ?? 0}% (${(options.diffPixels ?? 0).toLocaleString()} pixels mismatched)
- **Target URL:** ${options.url}
- **Detected At:** ${new Date().toUTCString()}

### Environment
- **OS:** ${os.type()} ${os.release()} (${os.arch()})
- **Engine:** Playwright Chromium (Automated Headless)
- **VS Code:** ${vscode.version}

${testIdsSection}
${errorsSection}
### Steps to Reproduce
1. Navigate to \`${options.url}\`
2. Compare rendered DOM and visual snapshot against approved baseline
3. Inspect visual difference and attribute mutations in DOM-Snap extension

---
*Generated by DOM-Snap for VS Code.*
`;
}

export async function exportBugReportCommand(): Promise<void> {
  const url = await vscode.window.showInputBox({
    prompt: 'Enter the target URL for the defect report',
    value: 'http://localhost:3000',
  });
  if (!url) return;

  const markdown = generateBugReportMarkdown({
    url,
    mismatchPercentage: 2.85,
    diffPixels: 2410,
    missingTestIds: ['submit-checkout-button'],
    consoleErrors: ['[TypeError] Failed to fetch customer session at checkout.js:84'],
  });

  await vscode.env.clipboard.writeText(markdown);

  const doc = await vscode.workspace.openTextDocument({
    language: 'markdown',
    content: markdown,
  });
  await vscode.window.showTextDocument(doc);

  vscode.window.showInformationMessage(
    'DOM-Snap: Defect report copied to clipboard and opened in editor!'
  );
}
